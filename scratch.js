console.log('연습1) 새 글', 새글?.length, '건   (정답: 2건)');

// TODO 2) 공지들 전부를 "[카테고리] 제목" 형태의 문자열 배열로 바꿔라.
//         힌트: map + 템플릿 리터럴(백틱)
const 문구들 = 공지들.map((c) => `[${c.category}] ${c.title}`); // ← 여기를 고쳐라
console.log('연습2)', 문구들);
// 정답 첫 줄: [학사] 주차장 이용 제한 안내

// TODO 3) 공지들 중 가장 큰 no 를 구해라.
//         힌트: 먼저 map 으로 no 만 뽑아 숫자 배열을 만든 뒤
//               Math.max(...숫자배열) 를 쓴다.  (... 은 "펼쳐서 넣어라" 라는 뜻)
