// -----------------------------------------------------------
// [1] const — 값에 이름 붙이기
//     const = 다시 대입 못 함. 기본은 무조건 const 를 쓴다.
//     let  = 나중에 바꿀 값에만 쓴다.
// -----------------------------------------------------------
const 학교 = 'GIST';
let 개수 = 0;
개수 = 3; // let 이라 가능. const 였으면 여기서 에러

console.log('[1]', 학교, 개수);


// -----------------------------------------------------------
// [2] 객체(object) — 이름표가 붙은 값 묶음
//     공지 하나를 이렇게 표현한다. 우리 파서가 만들어낼 모양.
// -----------------------------------------------------------
const 공지하나 = {
  no: 223132,
  category: '장학/납입금',
  title: '국가장학금 신청자 가구원 동의 안내',
  date: '2026-09-01',
};

console.log('[2]', 공지하나.no, '/', 공지하나.category);
//                 ^^^^^^^^^^^ 점(.)으로 안의 값을 꺼낸다


// -----------------------------------------------------------
// [3] 배열(array) — 순서 있는 목록
//     [] 안에 쉼표로 나열. 게시판 = 공지 객체들의 배열.
// -----------------------------------------------------------
const 공지들 = [
  { no: 223143, category: '학사', title: '주차장 이용 제한 안내', date: '2026-09-02' },
  { no: 223132, category: '장학/납입금', title: '국가장학금 가구원 동의', date: '2026-09-01' },
  { no: 223096, category: '국제협력', title: '해외 교환학생 선발', date: '2026-09-01' },
  { no: 223051, category: '학사', title: '재학생 성격검사 안내', date: '2026-08-31' },
];

console.log('[3] 총', 공지들.length, '건'); // .length = 개수


// -----------------------------------------------------------
// [4] 화살표 함수 — 값을 받아 값을 돌려주는 기계
//
//     const 이름 = (입력) => 결과;
//
//     예전 문법 function(x) { return x * 2 } 과 같은 뜻인데 짧다.
//     요즘 JS 코드는 거의 이걸 쓴다.
// -----------------------------------------------------------
const 두배 = (x) => x * 2;
console.log('[4]', 두배(21));

// 중괄호 {} 를 쓰면 여러 줄 쓸 수 있다. 대신 return 을 직접 써야 한다.
const 설명 = (공지) => {
  const 앞부분 = `${공지.no}번`;
  return 앞부분 + ' ' + 공지.title;
};
console.log('[4]', 설명(공지하나));


// -----------------------------------------------------------
// [5] map / filter / find — 배열 다루는 3대장
//     for 반복문 대신 이걸 쓴다. 우리 코드의 핵심.
//
//     filter : 조건에 맞는 것만 골라 → 배열
//     map    : 하나하나 변환해서    → 배열 (개수 그대로)
//     find   : 조건에 맞는 첫 하나  → 객체 하나 (배열 아님!)
// -----------------------------------------------------------
const 학사만 = 공지들.filter((c) => c.category === '학사');
console.log('[5] filter →', 학사만.length, '건');
//                                    ^^^ === 는 "같다" 비교. = 하나는 대입이니 주의

const 제목들 = 공지들.map((c) => c.title);
console.log('[5] map    →', 제목들);

const 찾은것 = 공지들.find((c) => c.no === 223096);
console.log('[5] find   →', 찾은것.title);

// 이어붙일 수도 있다 (체이닝). 왼쪽에서 오른쪽으로 흐른다.
const 학사제목 = 공지들
  .filter((c) => c.category === '학사')
  .map((c) => c.title);
console.log('[5] chain  →', 학사제목);


// -----------------------------------------------------------
// [6] 템플릿 리터럴 — 문자열 안에 값 끼워넣기
//     작은따옴표 ' 가 아니라 백틱 ` 을 쓴다. (키보드 1 왼쪽)
//     ${ } 안에 값이 들어간다.
// -----------------------------------------------------------
const 알림문구 = `[${공지하나.category}] ${공지하나.title}`;
console.log('[6]', 알림문구);


// -----------------------------------------------------------
// [7] async / await — 시간이 걸리는 일 기다리기
//     인터넷에서 페이지를 받아오는 건 즉시 안 끝난다.
//     await = "끝날 때까지 기다렸다가 결과를 줘"
//     await 를 쓰려면 그 함수에 async 가 붙어 있어야 한다.
// -----------------------------------------------------------
const 게시판주소 = 'https://www.gist.ac.kr/kr/html/sub05/050209.html';

const 받아오기 = async () => {
  const 응답 = await fetch(게시판주소); // 여기서 잠깐 멈춰서 기다림
  const html = await 응답.text();       // 본문을 글자로 (이것도 기다림)
  return html;
};

// await 없이 그냥 부르면? 결과 대신 "곧 줄게" 라는 약속(Promise)이 나온다.
console.log('[7] await 없이:', 받아오기());


