// ===========================================================
//  1단계 — 게시판 HTML 을 공지 객체 배열로 바꾼다
//
//  입력: GIST 학사공지 게시판 페이지 HTML (그냥 긴 문자열)
//  출력: [{ no, category, title, date }, ...]
//
//  왜 정규식인가:
//    Cloudflare Workers 에는 브라우저 DOM 이 없어서 document.querySelector
//    같은 걸 못 쓴다. cheerio 같은 라이브러리도 무겁다.
//    게시판 마크업이 아래처럼 완벽히 규칙적이라 정규식이 가장 짧다.
//
//  실제 게시판 한 줄은 이렇게 생겼다:
//
//    <tr id='BBSList223132' class='lstNtc'>
//      <td class=ntt_no>공지</td>
//      <td class=category>장학/납입금</td>
//      <td class=title> <a href='?mode=V&amp;no=223132'>[학사] 국가장학금 …</a> </td>
//      <td class=wrt>정서현</td>
//      <td class=inq_cnt>195</td>
//      <td class=reg_date>2026-09-01</td>
//    </tr>
// ===========================================================

// -----------------------------------------------------------
//  [제공] 정규식 4개
//
//  정규식 = "이런 모양의 글자를 찾아라" 라고 쓰는 패턴.
//  지금 문법을 이해할 필요 없다. 각각이 뭘 집어오는지만 알면 된다.
//  괄호 ( ) 로 감싼 부분이 "실제로 뽑아낼 값" 이다.
// -----------------------------------------------------------
const RE_NO = /^(\d+)/; //                          숫자 → 223132
const RE_CATEGORY = /class=category>([^<]*)/; //    카테고리 → 장학/납입금
const RE_TITLE = /class=title>[\s\S]*?<a[^>]*>([\s\S]*?)<\/a>/; //  제목
const RE_DATE = /class=reg_date>\s*([\d-]+)/; //    날짜 → 2026-09-01

// -----------------------------------------------------------
//  [제공] HTML 엔티티 되돌리기
//
//  HTML 안에서는 특수문자를 &amp; &#039; 같은 암호로 쓴다.
//  실제 게시판 제목에 &#039; (작은따옴표) 가 들어있는 걸 확인했다.
//  그대로 두면 알림에 "GIST&#039;s" 처럼 지저분하게 뜬다.
// -----------------------------------------------------------
const decode = (s) =>
  s
    .replace(/&#0?39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&'); // &amp; 는 반드시 마지막에 (안 그러면 이중 변환됨)

// -----------------------------------------------------------
//  [제공] 조각에서 값 하나 꺼내기
//
//  pick(조각, 정규식)  →  찾으면 그 글자(공백 정리 + 엔티티 복원), 없으면 ''
//
//  예:  pick(조각, RE_CATEGORY)  →  '장학/납입금'
// -----------------------------------------------------------
const pick = (chunk, re) => {
  const m = chunk.match(re);
  if (!m) return '';
  // 제목 안에 NEW 아이콘 <img ...> 가 끼어 있는 경우가 있다.
  // (게시판이 최근 글에만 붙이므로 오래된 픽스처에는 안 나온다)
  // 태그를 통째로 벗겨내고 남은 글자만 쓴다.
  return decode(m[1].replace(/<[^>]*>/g, '')).replace(/\s+/g, ' ').trim();
};

// ===========================================================
//  ★ 여기부터 네가 쓸 차례
// ===========================================================

export function parse(html) {
  // [제공] 긴 HTML 을 행 단위로 자른다.
  //
  //   split("<tr id='BBSList")  → 이 글자를 기준으로 문자열을 토막낸다
  //   .slice(1)                 → 첫 토막은 표가 시작되기 전의 쓰레기라 버린다
  //
  //   결과: chunks 는 문자열 배열. 각 원소가 공지 한 줄이고 이렇게 시작한다:
  //     "223132' class='lstNtc'>  <td class=ntt_no>공지</td> ..."
  //      ~~~~~~ 그래서 RE_NO 의 ^(\d+) 가 맨 앞 숫자를 집어올 수 있다
  const chunks = html.split("<tr id='BBSList").slice(1);

  // chunks(문자열 배열)를 공지 객체 배열로 바꾼다.
  // 워밍업 연습2와 같은 map. 다른 점은 문자열이 아니라 객체를 만든다는 것.
  // 화살표 함수가 객체를 바로 돌려줄 때는 소괄호로 감싸야 한다 — 안 그러면
  // JS 가 { 를 코드 블록의 시작으로 착각한다.
  return chunks.map((r) => ({
    no: Number(pick(r, RE_NO)), // 글자 '223132' → 숫자 223132
    category: pick(r, RE_CATEGORY),
    title: pick(r, RE_TITLE),
    date: pick(r, RE_DATE),
  }));
}
